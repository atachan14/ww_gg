    def test_two_independent_label_changes_preserve_entire_QP_law(self):
        def law(d,v):
            cap=build(d,v);e=cap.engine;s=cap.source
            rows=e.morning(s.public,s.public_state,s.past)
            weighted=e.push(s.public_state,s.private,rows)
