const {JSDOM}=require('jsdom'),fs=require('fs'),assert=require('assert');
const dom=new JSDOM('',{url:'https://example.test',runScripts:'outside-only'}),w=dom.window;
w.eval(fs.readFileSync('static/board_private_draft.js','utf8'));
const original=[{reporter:2,day:1,target:3,color:'white'}];
const setup={boardId:'game-night-2',revision:7,storage:w.sessionStorage};
const store=w.createBoardPrivateDraftStore(setup);
const row=store.open({player:2,role:'seer',claims:['seer'],publicResults:original});
assert.equal(row.results[0].target,3);row.results[0].target=99;
assert.equal(store.snapshot({player:2,role:'seer'}).results[0].target,3);
store.edit({player:2,role:'seer',results:[{day:1,target:4,color:'black'}]});
assert.equal(original[0].target,3);assert.equal(original[0].color,'white');
assert.equal(store.open({player:2,role:'seer',claims:['seer'],publicResults:original}).results[0].target,4);
store.edit({player:2,role:'seer',results:[]});
const restored=w.createBoardPrivateDraftStore(setup);assert.equal(restored.open({player:2,role:'seer',claims:['seer'],publicResults:original}).results.length,0);
assert.equal(store.open({player:3,role:'seer',claims:[],publicResults:[{reporter:3,day:1,target:2,color:'white'}]}).results.length,0);
assert.equal(store.open({player:2,role:'medium',claims:['seer'],publicResults:original}).results.length,0);
const revised=w.createBoardPrivateDraftStore({...setup,revision:8});assert.equal(revised.open({player:2,role:'seer',claims:['seer'],publicResults:original}).results[0].target,3);
assert.throws(()=>store.edit({player:2,role:'seer',results:[{day:1,target:3,color:'fake'}]}));
const scoped=w.createBoardPrivateDraftStore({...setup,scopeRevision:false});
scoped.open({player:2,role:'seer',claims:['seer'],publicResults:original});
scoped.edit({player:2,role:'seer',results:[{day:1,target:4,color:'black'}]});
const nextRevision=w.createBoardPrivateDraftStore({...setup,revision:8,scopeRevision:false});
assert.equal(nextRevision.open({player:2,role:'seer',claims:['seer'],publicResults:original}).results[0].target,4);
const otherBoard=w.createBoardPrivateDraftStore({...setup,boardId:'other-board',scopeRevision:false});
assert.equal(otherBoard.open({player:2,role:'seer',claims:[],publicResults:original}).results.length,0);
dom.window.close();console.log('Private draft: first-copy, independent edit, clear/reopen, per-view scope, revision isolation: PASS');
